#!/usr/bin/env python3
"""Generate server/src/abs/models/rows.rs from server/src/abs/schema.sql: one row struct per Audiobookshelf table.

Usage: scripts/abs-rows.py server/src/abs/schema.sql > server/src/abs/models/rows.rs && cargo fmt
"""
import re
import sys

sql = open(sys.argv[1], encoding="utf-8").read()
TYPES = {"UUID": "String", "VARCHAR": "String", "TEXT": "String", "DATETIME": "String", "JSON": "Value",
         "TINYINT": "bool", "INTEGER": "i64", "BIGINT": "i64", "FLOAT": "f64"}


def snake(name):
    s = re.sub(r"(?<!^)([A-Z])", r"_\1", name.replace("URL", "Url")).lower()
    return {"type": "kind"}.get(s, s)


def struct_name(table):
    singular = {"series": "Series", "mediaProgresses": "MediaProgress", "migrationsMeta": "MigrationsMeta",
                "libraryItems": "LibraryItem", "libraries": "Library", "bookSeries": "BookSeries"}
    if table in singular:
        return singular[table]
    t = table[:-1] if table.endswith("s") else table
    return t[0].upper() + t[1:]


print("//! Row types for every table of Audiobookshelf's database ([`super::super::SCHEMA`]), generated by")
print("//! `scripts/abs-rows.py` from `schema.sql`; do not edit by hand. Each struct keeps the column names of the")
print("//! original (camelCase in the database and in JSON) and the table's types: text, dates as the original")
print("//! writes them (`YYYY-MM-DD HH:MM:SS.SSS +00:00`), JSON columns as [`Value`], `TINYINT(1)` as `bool`. Every")
print("//! column is optional, as in the original (only `id`, `createdAt` and `updatedAt` are always set).")
print("//! Behaviour and the JSON the API sends live next to each model (`models/<model>.rs`), not here.")
print()
print("#![allow(missing_docs)]")
print()
print("use super::Table;")
print("use serde::{Deserialize, Serialize};")
print("use serde_json::Value;")
for m in re.finditer(r"CREATE TABLE `(\w+)` \((.*?)\);\n", sql, re.S):
    table, body = m.groups()
    cols = []
    for c in re.finditer(r"`(\w+)` (UUID|VARCHAR|TEXT|DATETIME|JSON|TINYINT|INTEGER|BIGINT|FLOAT)", body):
        name, typ = c.groups()
        if name in [x[0] for x in cols]:
            continue
        cols.append((name, typ))
    sname = struct_name(table)
    print()
    print(f"/// A row of `{table}`.")
    print("#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]")
    print('#[serde(rename_all = "camelCase", default)]')
    print(f"pub struct {sname} {{")
    for name, typ in cols:
        rust = TYPES[typ]
        field = snake(name)
        rename = f'    #[serde(rename = "{name}")]\n' if field == "kind" or re.sub(r"_([a-z])", lambda x: x.group(1).upper(), field) != name else ""
        print(f"{rename}    pub {field}: Option<{rust}>,")
    print("}")
    print()
    print(f"impl Table for {sname} {{")
    print(f'    const TABLE: &\'static str = "{table}";')
    print(f"    const COLUMNS: &'static [&'static str] = &[{', '.join(repr(n).replace(chr(39), chr(34)) for n, _ in cols)}];")
    print(f"    const JSON_COLUMNS: &'static [&'static str] = &[{', '.join(chr(34) + n + chr(34) for n, t in cols if t == 'JSON')}];")
    print(f"    const BOOL_COLUMNS: &'static [&'static str] = &[{', '.join(chr(34) + n + chr(34) for n, t in cols if t == 'TINYINT')}];")
    print("}")
